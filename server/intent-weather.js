const CITY_SORTED = [...new Set(CITIES)].sort((a, b) => b.length - a.length);

/** 兜底正则捕获到的伪城市词 */
const STOPWORDS = new Set([
  '今天', '明天', '后天', '昨天', '现在', '实时', '此刻', '当前', '最近', '最近几天',
  '天气', '气温', '如何', '怎样', '怎么样', '什么', '查询', '查查', '看下', '看看',
  '请问', '麻烦', '帮我', '一下', '那里', '哪里', '这边', '我们', '你们',
]);

/**
 * 兜底正则抠出的候选只要含这些词就一定是伪城市：
 * 「用户所在的城市」会被正则抠成「用户所在的城」，拿这种词去查接口纯属浪费额度。
 * 词表故意不用单字，避免误伤真实城市（如「本溪」不含「本地」）。
 */
const FAKE_CITY_WORDS = [
  '所在', '城市', '当地', '本地', '这里', '这边', '那里', '那边', '哪里',
  '用户', '地方', '区域', '位置', '地址', '朋友', '老师',
  '今天', '明天', '后天', '天气', '气温', '怎样', '如何',
];

function isFakeCity(c) {
  return !c || STOPWORDS.has(c) || FAKE_CITY_WORDS.some((w) => c.includes(w));
}

/** 词典没命中时，从「XX天气」「XX市气温」里抠城市 */
const FALLBACK_RE = /([一-龥]{2,7}?)(?:市|县|区|镇)?(?:的)?(?:今天|明天|后天)?(?:的)?(?:天气|气温)/;

function pickCity(text) {
  for (const c of CITY_SORTED) {
    if (text.includes(c)) return c;
  }
  const m = text.match(FALLBACK_RE);
  if (m) {
    const c = m[1].replace(/(市|县|区|镇)$/, '');
    if (!isFakeCity(c)) return c;
  }
  return null;
}

function pickDay(text) {
  if (/现在|实时|此刻|当前/.test(text)) return '实时';
  if (/后天/.test(text)) return '后天';
  if (/明天|明日/.test(text)) return '明天';
  if (/今天|今日/.test(text)) return '今天';
  return '实时';
}

/**
 * @param {string} text 用户当前这条消息
 * @returns {{hit:boolean, city:string|null, day:'实时'|'今天'|'明天'|'后天', needCity:boolean}}
 */
export function detectWeatherIntent(text) {
  const t = String(text || '').trim();
  if (!t || !INTENT_RE.test(t) || STATEMENT_RE.test(t)) {
    return { hit: false, city: null, day: '实时', needCity: false };
  }
  const city = pickCity(t);
  return { hit: true, city, day: pickDay(t), needCity: !city };
}

/** 天数词 → forecast 下标；实时返回 -1 */
export function dayIndex(day) {
  if (day === '后天') return 2;
  if (day === '明天') return 1;
  if (day === '今天') return 0;
  return -1;
}
